    "# چه استفاده‌ای می‌کنیم",
    "این اطلاعات فقط برای پردازش و ارسال سفارش، فرستادن پیامک وضعیت سفارش و پاسخ به درخواست‌های شما به کار می‌رود.",
    "# با چه کسی به اشتراک می‌گذاریم",
    "نام، شماره تماس و آدرس فقط در اختیار شرکت حمل‌ونقلی قرار می‌گیرد که سفارش را می‌رساند. اطلاعات شما به هیچ شخص یا شرکت دیگری فروخته یا داده نمی‌شود.",
