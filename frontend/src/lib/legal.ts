import { faNum } from "./format";
import type { Store } from "./types";

/*
 * Starting text for the terms and privacy pages, built from the store settings.
 * Shown until the owner writes their own in the panel. Lines starting with "# " are headings.
 */

export function defaultTerms(store: Store) {
  const r = store.returns;
  return [
    `استفاده از وب‌سایت ${store.name} و ثبت سفارش در آن به معنای پذیرفتن قوانین زیر است.`,
    "# ثبت سفارش",
    "برای خرید، با شماره موبایل خود و کد پیامکی وارد می‌شوید. مسئولیت درستی نام، شماره تماس و آدرس تحویل با خریدار است.",
    "قیمت همه‌ی کالاها به تومان است. قیمت نهایی، هزینه‌ی ارسال و تخفیف پیش از پرداخت در صفحه‌ی تسویه‌حساب نمایش داده می‌شود.",
    store.online_payment
      ? "سفارش پس از پرداخت موفق از درگاه بانکی قطعی می‌شود. سفارشی که در مهلت تعیین‌شده پرداخت نشود، خودکار لغو می‌شود."
      : "پس از ثبت سفارش، فروشگاه برای هماهنگی پرداخت با شما تماس می‌گیرد. سفارشی که در مهلت تعیین‌شده پرداخت نشود، خودکار لغو می‌شود.",
    "موجودی کالاها بین فروشگاه حضوری و سایت مشترک است. اگر کالایی هم‌زمان در فروشگاه فروخته شود و سفارش شما قابل تأمین نباشد، فروشگاه با شما تماس می‌گیرد و مبلغ پرداختی کامل بازگردانده می‌شود.",
    "# ارسال",
    "روش‌های ارسال و هزینه‌ی هر کدام در صفحه‌ی تسویه‌حساب آمده است. کد رهگیری مرسوله پس از ارسال برای شما پیامک می‌شود و در صفحه‌ی پیگیری سفارش هم دیده می‌شود.",
    "# مرجوعی و تعویض",
    r.enabled
      ? `کالا تا ${faNum(r.days)} روز پس از تحویل، به شرط استفاده‌نشدن، شسته‌نشدن و داشتن برچسب، ${r.type === "exchange" ? "قابل تعویض سایز" : "قابل تعویض یا بازگشت وجه"} است. جزئیات در صفحه‌ی قوانین مرجوعی آمده است.`
      : "امکان مرجوعی کالا وجود ندارد؛ لطفاً پیش از خرید جدول سایز را بررسی کنید.",
    "# لغو سفارش",
    "تا پیش از پرداخت، می‌توانید سفارش را از صفحه‌ی سفارش لغو کنید. برای لغو سفارش پرداخت‌شده‌ای که هنوز ارسال نشده، با فروشگاه تماس بگیرید تا مبلغ بازگردانده شود.",
    "# ارتباط با ما",
    [store.phone && `موبایل: ${store.phone}`, store.landline && `تلفن: ${store.landline}`, store.address && `آدرس: ${store.address}`].filter(Boolean).join(" · "),
  ].join("\n");
}

